const SAFE: ReadonlySet<string> = new Set(READ_ONLY_SAFE)

/**
 * Défense en profondeur (fiche 196) : en lecture seule, le gestionnaire refuse tout envoi, d'où
 * qu'il vienne (correction automatique d'une PR, tâche, outil d'un agent, renvoi d'un message
 * retenu). `prompt` lui-même est enveloppé : aucune garde (`promptGate`), dans aucun ordre de
 * démarrage, ne passe avant ce refus.
 */
export function guardPrompts(
  manager: { prompt: ConversationManager['prompt'] },
  readOnly: () => boolean
): void {
  const prompt = manager.prompt.bind(manager)
  manager.prompt = (...args) => (readOnly() ? Promise.reject(readOnlyError()) : prompt(...args))
}

/** En lecture seule, tout canal hors de `READ_ONLY_SAFE` est refusé. */
export function guardReadOnly(handlers: IpcHandlers, readOnly: () => boolean): IpcHandlers {
  const guarded = { ...handlers } as Record<string, (...args: unknown[]) => unknown>
  for (const [channel, handler] of Object.entries(handlers) as [
    string,
    (...a: unknown[]) => unknown
  ][]) {
    if (SAFE.has(channel)) continue
    guarded[channel] = (...args: unknown[]) => {
      if (readOnly()) throw readOnlyError()
      return handler(...args)
    }
  }
  return guarded as unknown as IpcHandlers
}
